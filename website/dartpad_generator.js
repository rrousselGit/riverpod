// Packs the examples that docs embed with `<DartPad example="name" />`, or
// link to with `/dartpad?example=name`, into
// src/dartpad_examples.js, as base64 tar.gz archives that DartPad loads
// through a data: URL. Compressed, as DartPad rejects longer URLs.
//
// gzip output can vary across zlib versions, so archives are compared once
// decompressed: an unchanged example keeps its committed archive.
//
// Usage: node dartpad_generator.js [--check]
//   --check   Don't write. Fail if the committed file is stale.

const fs = require("fs");
const glob = require("glob");
const path = require("path");
const zlib = require("zlib");

const docFiles = ["docs/**/*.mdx", "i18n/**/*.mdx"];
const examplesDir = "../examples";
const outFile = "./src/dartpad_examples.js";

function main() {
  const check = process.argv.includes("--check");

  const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, "utf8") : "";
  const committed = readArchives(current);

  let buffer = "// Generated by dartpad_generator.js. Do not edit.\n\n";
  buffer += "export const dartpadExamples = {\n";
  for (const name of findExampleNames()) {
    const archive = tar(exampleFiles(name));
    const previous = committed.get(name);
    const encoded =
      previous !== undefined && gunzipOrNull(previous)?.equals(archive)
        ? previous
        : zlib.gzipSync(archive, { level: 9 }).toString("base64");
    buffer += `  ${JSON.stringify(name)}: "${encoded}",\n`;
  }
  buffer += "};\n";

  if (current === buffer) {
    console.log(`${outFile} is up to date.`);
  } else if (check) {
    console.error(`${outFile} is out of date with the examples.`);
    console.error("Fix with: cd website && node dartpad_generator.js");
    process.exit(1);
  } else {
    fs.writeFileSync(outFile, buffer);
    console.log(`Updated ${outFile}.`);
  }
}

function readArchives(content) {
  const archives = new Map();
  for (const match of content.matchAll(/^  "([^"]+)": "([^"]*)",$/gm)) {
    archives.set(match[1], match[2]);
  }
  return archives;
}

function gunzipOrNull(base64) {
  try {
    return zlib.gunzipSync(Buffer.from(base64, "base64"));
  } catch {
    return null;
  }
}

function findExampleNames() {
  const names = new Set();
  for (const file of docFiles.flatMap((pattern) => glob.sync(pattern))) {
    const content = fs.readFileSync(file, "utf8");
    // Embeds, and links to the /dartpad page.
    const pattern = /<DartPad\s[^>]*example="([^"]+)"|\/dartpad\?example=([\w-]+)/g;
    for (const match of content.matchAll(pattern)) {
      const name = match[1] ?? match[2];
      if (!fs.existsSync(path.join(examplesDir, name, "pubspec.yaml"))) {
        throw new Error(`${file} uses a missing example: ${name}`);
      }
      names.add(name);
    }
  }
  return [...names].sort();
}

// The pubspec and lib/ of an example, as archive paths starting with its name
// (what DartPad's `root` and `file` parameters point to).
function exampleFiles(name) {
  const dir = path.join(examplesDir, name);
  return ["pubspec.yaml", ...glob.sync("lib/**/*", { cwd: dir, nodir: true, posix: true })]
    .sort()
    .map((file) => ({
      name: `${name}/${file}`,
      content: fs.readFileSync(path.join(dir, file)),
    }));
}

// A ustar archive. Owners, modes and dates are fixed so that the same files
// always give the same bytes, which --check relies on.
function tar(files) {
  const blocks = [];
  for (const file of files) {
    if (Buffer.byteLength(file.name) > 100) {
      throw new Error(`Path too long for a tar header: ${file.name}`);
    }
    const header = Buffer.alloc(512);
    header.write(file.name, 0);
    header.write("0000644\0", 100); // mode
    header.write("0000000\0", 108); // uid
    header.write("0000000\0", 116); // gid
    header.write(file.content.length.toString(8).padStart(11, "0") + "\0", 124);
    header.write("00000000000\0", 136); // mtime
    header.write("        ", 148); // checksum, counted as spaces
    header.write("0", 156); // regular file
    header.write("ustar\0" + "00", 257);
    let checksum = 0;
    for (const byte of header) checksum += byte;
    header.write(checksum.toString(8).padStart(6, "0") + "\0 ", 148);

    blocks.push(header, file.content);
    const padding = (512 - (file.content.length % 512)) % 512;
    blocks.push(Buffer.alloc(padding));
  }
  blocks.push(Buffer.alloc(1024));
  return Buffer.concat(blocks);
}

main();
